package com.example.samplecoupon.adapter.rest

import com.example.samplecoupon.adapter.ValidCouponCode
import com.example.samplecoupon.adapter.ValidRedemptionRequestId
import com.example.samplecoupon.adapter.ValidUserId
import com.example.samplecoupon.common.NormalizeFormat
import com.example.samplecoupon.common.NormalizeString
import com.example.samplecoupon.domain.GeoLocationClient
import com.example.samplecoupon.usecase.CouponRedeemUseCase
import com.example.samplecoupon.usecase.RedeemCouponCommand
import io.swagger.v3.oas.annotations.Operation
import io.swagger.v3.oas.annotations.media.Schema
import io.swagger.v3.oas.annotations.tags.Tag
import jakarta.servlet.http.HttpServletRequest
import jakarta.validation.Valid
import java.util.UUID
import org.springframework.http.HttpStatus.CREATED
import org.springframework.http.MediaType.APPLICATION_JSON_VALUE
import org.springframework.validation.annotation.Validated
import org.springframework.web.bind.annotation.PostMapping
import org.springframework.web.bind.annotation.RequestBody
import org.springframework.web.bind.annotation.RequestMapping
import org.springframework.web.bind.annotation.ResponseStatus
import org.springframework.web.bind.annotation.RestController

@Tag(name = "Coupon Redemption API", description = "Redeem coupons on behalf of users")
@RestController
@RequestMapping("/api/v1/coupon-redemptions")
@Validated
class CouponRedemptionController(
    private val couponRedeemUseCase: CouponRedeemUseCase,
    private val geoLocationClient: GeoLocationClient,
) {

  @Operation(
      operationId = "redeemCoupon",
      summary = "Redeem coupon",
      description =
          "Redeems a coupon for a user. The client's country is resolved from its IP address and must match the coupon's country. " +
              "Idempotent by requestId - repeating a request with the requestId of an already made redemption returns the same response without redeeming the coupon again, once the original request has completed.",
  )
  @PostMapping(consumes = [APPLICATION_JSON_VALUE], produces = [APPLICATION_JSON_VALUE])
  @ResponseStatus(CREATED)
  fun redeemCoupon(
      @RequestBody @Valid requestBody: RedeemCouponRequest,
      request: HttpServletRequest,
  ): RedeemCouponResponse {
    val identity = couponRedeemUseCase.redeemCoupon(requestBody.toCommand(request))
    return RedeemCouponResponse(requestId = identity.id)
  }

  private fun RedeemCouponRequest.toCommand(request: HttpServletRequest): RedeemCouponCommand {
    val geoLocation = geoLocationClient.findLocation(request.clientIpAddr)
    return RedeemCouponCommand(
        code = code,
        userId = UUID.fromString(userId),
        geoLocation = geoLocation,
        requestId = requestId?.let { UUID.fromString(it) },
    )
  }

  private val HttpServletRequest.clientIpAddr: String
    get() {
      return if (getHeader("X-Forwarded-For") == null) {
        remoteAddr
      } else {
        getHeader("X-Forwarded-For").split(",").first().trim()
      }
    }
}

data class RedeemCouponRequest(
    //
    @Schema(example = "SUMMER2026")
    @NormalizeString(trim = true, normalizeFormat = NormalizeFormat.UPPERCASE)
    @ValidCouponCode
    val code: String,
    //
    @Schema(example = "00000000-0000-0000-0000-000000000000")
    @ValidUserId //
    val userId: String,
    //
    @Schema(
        example = "00000000-0000-0000-0000-000000000000",
        description = "Idempotency key chosen by the caller. Generated by the server if omitted.",
    )
    @ValidRedemptionRequestId //
    val requestId: String? = null,
)

data class RedeemCouponResponse(
    @Schema(example = "00000000-0000-0000-0000-000000000000") val requestId: String,
)
