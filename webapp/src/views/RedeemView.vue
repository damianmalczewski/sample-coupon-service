<script setup>
import { reactive, ref } from 'vue'
import { useRoute } from 'vue-router'
import { describeError, redeemCoupon } from '../api.js'

const route = useRoute()

const form = reactive({ code: route.query.code ?? '', userId: '', requestId: '' })
const submitting = ref(false)
const result = ref(null)

const randomUuid = () => crypto.randomUUID()

async function submit() {
  submitting.value = true
  result.value = null
  try {
    const response = await redeemCoupon({
      code: form.code,
      userId: form.userId.trim(),
      requestId: form.requestId.trim() || undefined,
    })
    result.value = { ok: true, text: `Redeemed, request ${response.requestId}` }
  } catch (error) {
    const code = error.problem?.code ? `${error.problem.code}: ` : ''
    result.value = { ok: false, text: code + describeError(error) }
  } finally {
    submitting.value = false
  }
}
</script>

<template>
  <section class="panel">
    <h2>Redeem coupon</h2>
    <form class="stack" @submit.prevent="submit">
      <label>
        Code
        <input v-model="form.code" required maxlength="255" pattern="[a-zA-Z0-9]+" />
      </label>
      <label>
        User ID
        <span class="row">
          <input v-model="form.userId" class="mono grow" required placeholder="UUID" />
          <button type="button" @click="form.userId = randomUuid()">Random</button>
        </span>
      </label>
      <label>
        <span>Request ID <span class="muted">(optional, idempotency key)</span></span>
        <span class="row">
          <input v-model="form.requestId" class="mono grow" placeholder="UUID, generated by server if empty" />
          <button type="button" @click="form.requestId = randomUuid()">Random</button>
        </span>
      </label>
      <div>
        <button :disabled="submitting">Redeem</button>
      </div>
    </form>
    <p v-if="result" :class="result.ok ? 'ok' : 'error'">{{ result.text }}</p>
  </section>
</template>
