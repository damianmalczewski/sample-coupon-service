<script setup>
import { computed, onMounted, reactive, ref, watch } from 'vue';
import { useRoute } from 'vue-router';
import { describeError, listCoupons, redeemCoupon } from '../api.js';

const route = useRoute();

const form = reactive({ code: route.query.code ?? '', userId: '', requestId: '' });
const submitting = ref(false);
const result = ref(null);

const randomUuid = () => crypto.randomUUID();

// preview of the coupon behind the entered code: null while unknown, false when there is none
const coupon = ref(null);
const exhausted = computed(
  () => coupon.value && coupon.value.usageCount >= coupon.value.usageLimit,
);
let lookupSeq = 0;

async function lookupCoupon() {
  const seq = ++lookupSeq;
  const code = form.code.trim();
  if (!/^[a-zA-Z0-9]+$/.test(code)) {
    coupon.value = null;
    return;
  }
  try {
    const page = await listCoupons({ page: 0, size: 1, code });
    if (seq === lookupSeq) {
      coupon.value = page.content[0] ?? false;
    }
  } catch {
    if (seq === lookupSeq) {
      coupon.value = null;
    }
  }
}

let lookupTimer;
watch(
  () => form.code,
  () => {
    clearTimeout(lookupTimer);
    lookupTimer = setTimeout(lookupCoupon, 300);
  },
);
onMounted(lookupCoupon);

async function submit() {
  submitting.value = true;
  result.value = null;
  try {
    const response = await redeemCoupon({
      code: form.code,
      userId: form.userId.trim(),
      requestId: form.requestId.trim() || undefined,
    });
    result.value = { ok: true, text: `Redeemed, request ${response.requestId}` };
    lookupCoupon();
  } catch (error) {
    const code = error.problem?.code ? `${error.problem.code}: ` : '';
    result.value = { ok: false, text: code + describeError(error) };
  } finally {
    submitting.value = false;
  }
}
</script>

<template>
  <section class="panel">
    <h2>Redeem coupon</h2>
    <form class="stack" @submit.prevent="submit">
      <label>
        Code
        <input v-model="form.code" required maxlength="255" pattern="[a-zA-Z0-9]+" />
        <span v-if="coupon" class="muted">
          Country {{ coupon.countryCode }} · used {{ coupon.usageCount }} / {{ coupon.usageLimit }}
          <span v-if="exhausted" class="error">· limit reached</span>
        </span>
        <span v-else-if="coupon === false" class="muted">No coupon with this code</span>
      </label>
      <label>
        User ID
        <span class="row">
          <input v-model="form.userId" class="mono grow" required placeholder="UUID" />
          <button type="button" @click="form.userId = randomUuid()">Random</button>
        </span>
      </label>
      <label>
        <span>
          Request ID
          <span class="muted">(optional, idempotency key)</span>
        </span>
        <span class="row">
          <input
            v-model="form.requestId"
            class="mono grow"
            placeholder="UUID, generated by server if empty"
          />
          <button type="button" @click="form.requestId = randomUuid()">Random</button>
        </span>
      </label>
      <div>
        <button :disabled="submitting">Redeem</button>
      </div>
    </form>
    <p v-if="result" :class="result.ok ? 'ok' : 'error'">{{ result.text }}</p>
  </section>
</template>
